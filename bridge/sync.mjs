#!/usr/bin/env node
// Single source of truth = .opencode/{agents,commands,skills}. This generates the copies other tools read:
//   .claude/agents/*.md      Claude Code subagents      (from agents with mode: subagent)
//   .claude/commands/*.md    Claude Code slash commands (from commands, minus memory ones)
//   .claude/orchestrator.md  orchestrator rules imported by CLAUDE.md
//   .claude/skills           symlink -> .opencode/skills (Claude Code and Cline both read it)
//   .clinerules/workflows/*  Cline workflows that run the real opencode command through bin/oc
// Run: node .opencode/bridge/sync.mjs   (re-run after editing agents/commands)
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const oc = join(dirname(fileURLToPath(import.meta.url)), "..")
const root = join(oc, "..")
const GEN = "<!-- GENERATED by .opencode/bridge/sync.mjs — edit the source in .opencode/, then re-run sync. -->"
const SKIP_AGENTS = new Set(["memory-manager"]) // needs Hermes MCP tools, only available in opencode
const SKIP_COMMANDS = new Set(["memory", "memory-status", "memory-search", "compact", "forget", "help"])
const TOOL_MAP = { read: "Read", write: "Write", edit: "Edit", grep: "Grep", glob: "Glob", list: "Glob", bash: "Bash", webfetch: "WebFetch", task: "Task" }

function parse(file) {
  const src = readFileSync(file, "utf8")
  const m = src.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  const meta = {}
  const tools = {}
  let inTools = false
  for (const line of (m?.[1] ?? "").split("\n")) {
    const t = line.match(/^ {2}(\w+):\s*(true|false)/)
    if (inTools && t) tools[t[1]] = t[2] === "true"
    else {
      inTools = false
      const kv = line.match(/^(\w+):\s*(.*)$/)
      if (kv) {
        meta[kv[1]] = kv[2]
        inTools = kv[1] === "tools"
      }
    }
  }
  return { meta, tools, body: (m?.[2] ?? src).trim() }
}

const names = (dir) => readdirSync(join(oc, dir)).filter((f) => f.endsWith(".md")).map((f) => f.slice(0, -3))
const write = (path, text) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
}
const clean = (dir, keep) => {
  if (!existsSync(dir)) return
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".md") || keep.has(f.slice(0, -3))) continue
    const file = join(dir, f)
    if (readFileSync(file, "utf8").includes(GEN)) rmSync(file) // never delete hand-written files
  }
}

// Agents
const agents = new Set()
for (const id of names("agents")) {
  const { meta, tools, body } = parse(join(oc, "agents", `${id}.md`))
  if (id === "orchestrator") {
    // Arsa/Hermes memory exists only in opencode: drop its gate, writeback and roster line from the Claude copy.
    const claudeBody = body
      .replace(/^## Memory first[\s\S]*?(?=^## Handoffs)/m, "")
      .replace(/^## Memory writeback[\s\S]*?(?=^## Pausing)/m, "")
      .replace(/^- memory-manager .*\n/m, "")
    write(join(root, ".claude/orchestrator.md"), `${GEN}\n\n${claudeBody}\n`)
    continue
  }
  if (meta.mode !== "subagent" || SKIP_AGENTS.has(id)) continue
  const claudeTools = [...new Set(Object.entries(tools).filter(([k, v]) => v && TOOL_MAP[k]).map(([k]) => TOOL_MAP[k]))]
  agents.add(id)
  write(
    join(root, ".claude/agents", `${id}.md`),
    `---\nname: ${id}\ndescription: ${meta.description}\ntools: ${claudeTools.join(", ")}\n---\n${GEN}\n\n${body}\n`,
  )
}
clean(join(root, ".claude/agents"), agents)

// Commands
const commands = new Set()
for (const id of names("commands")) {
  if (SKIP_COMMANDS.has(id)) continue
  const { meta, body } = parse(join(oc, "commands", `${id}.md`))
  const direct = meta.agent && meta.agent !== "orchestrator" ? meta.agent : null
  commands.add(id)
  const claudeIntro = direct
    ? `Delegate this directly to the \`${direct}\` subagent (Task tool, subagent_type "${direct}").`
    : "You are the orchestrator (see CLAUDE.md). Delegate each step to the named subagents with the Task tool (subagent_type = agent id)."
  write(join(root, ".claude/commands", `${id}.md`), `---\ndescription: ${meta.description}\n---\n${GEN}\n\n${claudeIntro}\n\n${body}\n`)
  write(
    join(root, ".clinerules/workflows", `${id}.md`),
    `${GEN}\n\n# /${id} — ${meta.description}\n\n` +
      `Do not do the work yourself. Run the real OpenCode workflow (it drives the agent roster and lights up the visualizer):\n\n` +
      `\`\`\`bash\n.opencode/bin/oc cmd ${id} "<the user's request for this workflow>"\n\`\`\`\n\n` +
      `Wait for it to finish (can take several minutes), then report its result and any REQUIRED_FIXES or NOTES verbatim-short. ` +
      `If it fails, say so with the error — do not redo the work manually.\n`,
  )
}
clean(join(root, ".claude/commands"), commands)
clean(join(root, ".clinerules/workflows"), commands)

// Skills: symlink so there is one copy
const link = join(root, ".claude/skills")
let linkable = true
try {
  const st = lstatSync(link)
  if (st.isSymbolicLink()) rmSync(link)
  else {
    linkable = false
    console.warn(`warning: ${link} is a real ${st.isDirectory() ? "directory" : "file"}, not a symlink; skipping (remove it manually to link)`)
  }
} catch {} // missing: nothing to remove
if (linkable) symlinkSync("../.opencode/skills", link)

console.log(`agents: ${[...agents].join(", ")}\ncommands: ${[...commands].join(", ")}\nskills: ${linkable ? "symlinked" : "skipped"}`)

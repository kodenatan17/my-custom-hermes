#!/usr/bin/env node
// Single source of truth = .opencode/{agents,commands,skills}. Hermes (the Hermes Agent OS, ~/ferry-dev/hermes-agent-os)
// orchestrates the OpenCode and Cline entry points: they submit work to it through .opencode/bin/oc. Claude Code is
// standalone: its own session orchestrates the same specialists as native subagents on Claude models only (no Hermes,
// no 9Router, no Knowledge Graph). This generates:
//   .clinerules/workflows/*  Cline workflows that submit the route to Hermes
//   .claude/agents/*         the specialists as Claude Code subagents (model from CLAUDE_MODELS below)
//   .claude/commands/*       the agent routes as Claude Code slash commands, run by the Claude session itself
//   .claude/skills           symlink -> .opencode/skills (domain skills, no Hermes routing)
// Stale generated Claude files (e.g. .claude/hermes.md, .claude/orchestrator.md) are removed; hand-written ones never are.
// Run: node .opencode/bridge/sync.mjs   (re-run after editing agents/commands)
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, symlinkSync, unlinkSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const oc = join(dirname(fileURLToPath(import.meta.url)), "..")
const root = join(oc, "..")
const GEN = "<!-- GENERATED by .opencode/bridge/sync.mjs — edit the source in .opencode/, then re-run sync. -->"

function parse(file) {
  const src = readFileSync(file, "utf8")
  const m = src.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  const meta = {}
  for (const line of (m?.[1] ?? "").split("\n")) {
    const kv = line.match(/^(\w+):\s*(.*)$/)
    if (kv) meta[kv[1]] = kv[2]
  }
  return { meta, body: (m?.[2] ?? src).trim() }
}

const names = (dir) => readdirSync(join(oc, dir)).filter((f) => f.endsWith(".md")).map((f) => f.slice(0, -3))
const write = (path, text) => {
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
}
const isGenerated = (file) => existsSync(file) && readFileSync(file, "utf8").includes(GEN)
const clean = (dir, keep) => {
  if (!existsSync(dir)) return
  for (const f of readdirSync(dir)) {
    if (!f.endsWith(".md") || keep.has(f.slice(0, -3))) continue
    const file = join(dir, f)
    if (isGenerated(file)) rmSync(file) // never delete hand-written files
  }
}

// How Cline follows a running task. Progress lines come from `oc wait`: Hermes' steps, each agent
// started/finished (status, duration, warnings), tool failures, and a heartbeat that flags stalls.
const follow = [
  "Then run `.opencode/bin/oc wait <task_id> --max 540` with the printed task id (it blocks up to 9 minutes; allow a",
  "600000 ms command timeout). It streams progress lines live in the terminal (Hermes' steps, agents started/finished,",
  "⚠ failures or stalls). After each `wait`, tell the user in one to three short lines what happened since the last",
  "update, then repeat `wait` only while it prints `running` — do not poll faster.",
]

// Instructions for Cline, which reaches Hermes through the shell.
const submit = (route, arg) =>
  [
    "Hermes is the orchestrator of this workspace: do not do this work yourself and do not delegate to subagents.",
    "Submit it to Hermes with the shell, passing the request through the quoted heredoc exactly as written:",
    "",
    "```bash",
    `.opencode/bin/oc ${route} --async <<'AGENT_OS_REQUEST'`,
    arg,
    "AGENT_OS_REQUEST",
    "```",
    "",
    "One conversation is one Hermes task: if an earlier submit in this conversation printed a task id, put `--task`",
    `and that id right after \`--async\` (e.g. \`.opencode/bin/oc ${route} --async --task T-20261023-1621-example-0d72\`)`,
    "so Hermes continues that task (it resumes its own session and remembers the earlier turns). Put `--new` there",
    "instead only when the user asks for a separate task. On `task_busy`, `wait` on that task first.",
    "",
    ...follow,
    "Report Hermes' answer (after the `Hermes answer` line) as is (Summary · Executions · Files changed · Review/tests ·",
    "Memory · Unverified), without redoing, extending or re-checking the work. If `oc` fails, report the error.",
  ].join("\n")

// Claude Code: the specialists as native subagents, Claude models only. The tier follows the 9Router combo name
// (…-high/architect → opus, …-low → haiku, the rest → sonnet); change a model here, then re-run sync.
const CLAUDE_MODELS = {
  scout: "sonnet",
  architect: "opus",
  coder: "opus",
  qa: "sonnet",
  reviewer: "opus",
  documenter: "haiku",
  devops: "sonnet",
}
const CLAUDE_TOOLS = { read: ["Read"], write: ["Write"], edit: ["Edit"], grep: ["Grep"], glob: ["Glob"], bash: ["Bash"], webfetch: ["WebFetch", "WebSearch"] }
// OpenCode-only lines in the agent bodies (tool naming, Hermes' memory injection).
const claudeBody = (body) =>
  body
    .split("\n")
    .filter((line) => !line.includes("the tool name is exactly `shell`"))
    .join("\n")
    .replace("Use MEMORY CONTEXT first; don't re-discover what it already states.", "Use the context in the task first; don't re-discover what it already states.")
    .replace("via webfetch", "via WebFetch/WebSearch")

function agentTools(file) {
  const src = readFileSync(file, "utf8")
  const block = src.match(/^tools:\n((?:[ \t]+\w+:.*\n)+)/m)?.[1] ?? ""
  const tools = ["Skill"]
  for (const [, name, on] of block.matchAll(/^[ \t]+(\w+):\s*(\w+)/gm)) if (on === "true") tools.push(...(CLAUDE_TOOLS[name] ?? []))
  return tools
}

const agents = new Set()
for (const id of names("agents")) {
  if (!(id in CLAUDE_MODELS)) continue // `hermes` (the OpenCode front door) has no Claude counterpart
  const file = join(oc, "agents", `${id}.md`)
  const { meta, body } = parse(file)
  agents.add(id)
  write(
    join(root, ".claude/agents", `${id}.md`),
    `---\nname: ${id}\ndescription: ${meta.description}\ntools: ${agentTools(file).join(", ")}\nmodel: ${CLAUDE_MODELS[id]}\n---\n\n${GEN}\n\n${claudeBody(body)}\n`,
  )
}
for (const id of Object.keys(CLAUDE_MODELS)) if (!agents.has(id)) console.warn(`warning: CLAUDE_MODELS lists ${id}, but .opencode/agents/${id}.md is missing`)
clean(join(root, ".claude/agents"), agents)

// Agent routes -> Claude Code slash commands that the Claude session orchestrates itself. Knowledge Graph routes
// (memory*, compact, forget) belong to Hermes and help/compact would shadow Claude Code built-ins: not generated.
const HERMES_ONLY = new Set(["help", "memory", "memory-status", "memory-search", "compact", "forget"])
const orchestrate = [
  "You are the orchestrator for this route: Claude Code only — no Hermes, no 9Router, no `.opencode/bin/oc`.",
  "Run the route below with the Agent tool, one specialist per step, `subagent_type` = the agent name (scout, architect,",
  "coder, qa, reviewer, documenter, devops). Each step's prompt must stand alone: the user's request, the mode, what the",
  "earlier steps found (files, findings, design, changed files) and which skills to load.",
  "",
  "- Run steps in order; tell the user in one short line which agent finished with which STATUS before the next step.",
  "- Review loop: on reviewer FAIL, give its REQUIRED_FIXES to coder(fix), then re-run reviewer. At most 2 rounds, then stop and report.",
  "- A FAIL or NEEDS_REVISION you cannot resolve from the reports, or an OPEN question only the user can answer: stop and ask.",
  "- Do not redo a specialist's work yourself; only trivial glue between steps.",
  "- Final answer: Summary · Steps (agent → STATUS) · Files changed · Review/tests (real command output) · Open.",
].join("\n")
const claudeRoute = (body) =>
  body
    .split("\n")
    .map((line) => line.replace(/\s*Memory: .*$/, ""))
    .filter((line, i, all) => line.trim() || all[i - 1]?.trim())
    .join("\n")
    .trim()

const claudeCommands = new Set()
for (const id of names("commands")) {
  if (HERMES_ONLY.has(id)) continue
  const { meta, body } = parse(join(oc, "commands", `${id}.md`))
  claudeCommands.add(id)
  write(
    join(root, ".claude/commands", `${id}.md`),
    `---\ndescription: ${meta.description}\nargument-hint: <request>\n---\n\n${GEN}\n\n${orchestrate}\n\n${claudeRoute(body)}\n`,
  )
}
clean(join(root, ".claude/commands"), claudeCommands)
for (const stale of [join(root, ".claude/hermes.md"), join(root, ".claude/orchestrator.md")]) if (isGenerated(stale)) rmSync(stale)

// Commands -> Cline workflows (all submit to Hermes)
const commands = new Set()
for (const id of names("commands")) {
  const { meta } = parse(join(oc, "commands", `${id}.md`))
  commands.add(id)
  write(
    join(root, ".clinerules/workflows", `${id}.md`),
    `${GEN}\n\n# /${id} — ${meta.description}\n\n${submit(id, "<the user's request for this workflow, verbatim>")}\n`,
  )
}
clean(join(root, ".clinerules/workflows"), commands)

// Skills: symlink so there is one copy
const link = join(root, ".claude/skills")
let linkable = true
try {
  const st = lstatSync(link)
  if (st.isSymbolicLink()) unlinkSync(link) // rmSync refuses a link to a directory (ERR_FS_EISDIR)
  else {
    linkable = false
    console.warn(`warning: ${link} is a real ${st.isDirectory() ? "directory" : "file"}, not a symlink; skipping (remove it manually to link)`)
  }
} catch {} // missing: nothing to remove
if (linkable) symlinkSync("../.opencode/skills", link)

console.log(
  `claude: ${agents.size} agents, ${claudeCommands.size} commands (Claude models, no Hermes)\ncline: ${commands.size} workflows\nskills: ${linkable ? "symlinked" : "skipped"}`,
)
